import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomBytes, randomUUID, pbkdf2Sync} from 'node:crypto';
import {localDB} from './d1-local.mjs';

const module = await import('data:text/javascript;base64,' + (await readFile('dist/server/index.js')).toString('base64'));
const DB = localDB(), env = {DB}, origin = 'https://entity-one.test';
const credentials = {username:'analytics-owner',password:randomBytes(24).toString('base64url')};
const salt = randomBytes(32).toString('hex'), hash = pbkdf2Sync(credentials.password,salt,600000,32,'sha256').toString('hex');
let assertions = 0;
async function call(route, method='GET', value, auth={}, expected=200, cf) {
  const request = new Request(origin+route,{method,headers:{Origin:origin,'Content-Type':'application/json','User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130.0.0.0 Safari/537.36','CF-Connecting-IP':'198.51.100.8',...auth},...(value===undefined?{}:{body:JSON.stringify(value)})});
  if(cf) Object.defineProperty(request,'cf',{value:cf});
  const response = await module.default.fetch(request,env,{});
  const data = await response.json();
  assert.equal(response.status,expected,`${method} ${route}: unexpected response status (${data.error||''})`); assertions++;
  return {data,response};
}
const authentication = result => ({Cookie:result.response.headers.get('Set-Cookie').split(';')[0],'X-CSRF-Token':result.data.csrfToken});
const event = (type='page_view',path='/',target='') => ({id:randomUUID(),type,path,target});
const packet = (...events) => ({visitId:randomUUID(),referrer:'',events});
try {
  await DB.prepare('INSERT INTO administrator(id,username,salt,hash,hash_version) VALUES(1,?,?,?,?)').bind(credentials.username,salt,hash,module.PASSWORD_VERSION).run();
  const owner = authentication(await call('/api/login','POST',credentials));
  await call('/api/analytics','GET',undefined,{},401);
  const empty = (await call('/api/analytics','GET',undefined,owner)).data;
  assert.equal(empty.totals.pageViews,0);
  const publicContent = (await call('/api/content')).data.content;
  const car = publicContent.listings.find(x=>x.type==='inventory');
  const data = packet(event(),event('car_view','/',car.id),event('region_click','/inventory','Europe'));
  await call('/api/analytics/events','POST',data,{},202,{country:'GB'});
  await call('/api/analytics/events','POST',data,{},202,{country:'GB'});
  let report = (await call('/api/analytics','GET',undefined,owner)).data;
  assert.equal(report.totals.visits,1); assert.equal(report.totals.pageViews,1);
  assert.equal(report.totals.clicks,2); assert.equal(report.totals.carViews,1); assert.equal(report.totals.regionClicks,1);
  assert.equal(report.cars.find(x=>x.id===car.id).views,1);
  assert.equal(report.countries.find(x=>x.key==='GB').visits,1);
  await call('/api/analytics/events','POST',packet(event()),owner,202,{country:'US'});
  assert.equal((await call('/api/analytics','GET',undefined,owner)).data.totals.visits,1,'Signed-in staff excluded');
  await call('/api/analytics/events','POST',packet(event()),{Origin:'https://foreign.test'},403);
  await call('/api/analytics/events','POST',packet(event()),{Origin:''},403);
  await call('/api/analytics/events','POST',packet(event()),{'Content-Type':'text/plain'},415);
  await call('/api/analytics/events','POST',packet(event('page_view','/admin')),{},400);
  const stale = await call('/api/analytics/events','POST',packet(event('car_view','/inventory','nonexistent-private-record')),{},202);
  assert.equal(stale.data.recorded,0,'Stale or private car IDs never become analytics records');
  await call('/api/analytics/events','POST',{...packet(event()),secret:'x'.repeat(17000)}, {},413);
  await call('/api/analytics/events','POST',packet(event()),{DNT:'1'},202);
  await call('/api/analytics/events','POST',packet(event()),{'Sec-GPC':'1'},202);
  await call('/api/analytics/events','POST',packet(event()),{'User-Agent':'Googlebot/2.1'},202);
  assert.equal((await call('/api/analytics','GET',undefined,owner)).data.totals.visits,1,'Opt-outs and bots excluded');
  await call('/api/analytics/events','POST',packet(event()),{'CF-IPCountry':'US'},202);
  report = (await call('/api/analytics','GET',undefined,owner)).data;
  assert.ok(report.countries.some(x=>x.key==='XX'),'Untrusted location header cannot override missing edge metadata');
  const filtered = (await call('/api/analytics?country=GB&device=desktop','GET',undefined,owner)).data;
  assert.equal(filtered.totals.visits,1);
  assert.equal((await call('/api/analytics?country=US','GET',undefined,owner)).data.totals.visits,0);
  await call('/api/analytics?from=2026-02-30&to=2026-03-01','GET',undefined,owner,400);
  await call('/api/analytics?device=unbounded','GET',undefined,owner,400);
  const created = (await call('/api/users','POST',{username:'analyst-test',role:'viewer',permissions:['analytics.read']},owner,201)).data;
  let login = await call('/api/login','POST',{username:'analyst-test',password:created.temporaryPassword});
  await call('/api/analytics','GET',undefined,authentication(login),403);
  const nextPassword = randomBytes(24).toString('base64url');
  login = await call('/api/account/password','POST',{currentPassword:created.temporaryPassword,newPassword:nextPassword,confirmPassword:nextPassword},authentication(login));
  const analyst = authentication(login);
  await call('/api/analytics','GET',undefined,analyst);
  await call('/api/logs','GET',undefined,analyst,403);
  await call('/api/users/'+created.user.id,'PUT',{permissions:[]},owner);
  await call('/api/analytics','GET',undefined,analyst,401);
  login = await call('/api/login','POST',{username:'analyst-test',password:nextPassword});
  await call('/api/analytics','GET',undefined,authentication(login),403);
  const auditEvents = (await call('/api/logs','GET',undefined,owner)).data.events;
  assert.ok(!auditEvents.some(x=>x.action.startsWith('analytics.')),'Visitor telemetry never enters staff audit/Discord');
  assert.ok(!JSON.stringify(report).includes('198.51.100.8'));
  console.log(`PASS: ${assertions} analytics API checks covering collection, deduplication, aggregation, staff exclusion, permissions, password gate, origin limits, opt-outs and safe metadata.`);
} finally { DB.close(); }
